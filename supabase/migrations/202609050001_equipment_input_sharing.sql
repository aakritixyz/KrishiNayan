-- Equipment Listings RLS Policies
create policy "owners can view own listings" on public.equipment_listings
  for select using (auth.uid()::integer = owner_id);

create policy "owners can insert own listings" on public.equipment_listings
  for insert with check (auth.uid()::integer = owner_id);

create policy "owners can update own listings" on public.equipment_listings
  for update using (auth.uid()::integer = owner_id);

create policy "owners can delete own listings" on public.equipment_listings
  for delete using (auth.uid()::integer = owner_id);

create policy "everyone can view active listings" on public.equipment_listings
  for select using (status = 'active' and is_available = true);

-- Rental Requests RLS Policies
create policy "users can view own requests" on public.equipment_rental_requests
  for select using (auth.uid()::integer = renter_id or auth.uid()::integer = owner_id);

create policy "renters can create requests" on public.equipment_rental_requests
  for insert with check (auth.uid()::integer = renter_id);

create policy "owners can update requests" on public.equipment_rental_requests
  for update using (auth.uid()::integer = owner_id);

create policy "renters can update own requests" on public.equipment_rental_requests
  for update using (auth.uid()::integer = renter_id);

-- Reviews RLS Policies
create policy "users can view all reviews" on public.equipment_reviews
  for select using (true);

create policy "verified renters can create reviews" on public.equipment_reviews
  for insert with check (
    auth.uid()::integer = reviewer_id and 
    verified_rental = true
  );

-- Input Sharing RLS Policies
create policy "sellers can view own listings" on public.input_sharing_listings
  for select using (auth.uid()::integer = seller_id);

create policy "sellers can insert own listings" on public.input_sharing_listings
  for insert with check (auth.uid()::integer = seller_id);

create policy "sellers can update own listings" on public.input_sharing_listings
  for update using (auth.uid()::integer = seller_id);

create policy "sellers can delete own listings" on public.input_sharing_listings
  for delete using (auth.uid()::integer = seller_id);

create policy "everyone can view active input listings" on public.input_sharing_listings
  for select using (status = 'active' and is_available = true);

-- Bulk Purchase RLS Policies
create policy "organizers can view own groups" on public.bulk_purchase_groups
  for select using (auth.uid()::integer = organizer_id);

create policy "organizers can create groups" on public.bulk_purchase_groups
  for insert with check (auth.uid()::integer = organizer_id);

create policy "organizers can update own groups" on public.bulk_purchase_groups
  for update using (auth.uid()::integer = organizer_id);

create policy "everyone can view open groups" on public.bulk_purchase_groups
  for select using (status = 'open');

-- Bulk Purchase Participants RLS Policies
create policy "participants can view own participations" on public.bulk_purchase_participants
  for select using (auth.uid()::integer = participant_id);

create policy "users can join groups" on public.bulk_purchase_participants
  for insert with check (auth.uid()::integer = participant_id);

create policy "participants can update own participations" on public.bulk_purchase_participants
  for update using (auth.uid()::integer = participant_id);

-- Equipment Categories RLS Policies
create policy "everyone can view categories" on public.equipment_categories
  for select using (is_active = true);

-- User Equipment Trust RLS Policies
create policy "users can view own trust" on public.user_equipment_trust
  for select using (auth.uid()::integer = user_id);

create policy "everyone can view trust scores" on public.user_equipment_trust
  for select using (true);

-- Messages RLS Policies
create policy "participants can view request messages" on public.equipment_messages
  for select using (
    auth.uid()::integer in (
      select renter_id from public.equipment_rental_requests where id = rental_request_id
      union
      select owner_id from public.equipment_rental_requests where id = rental_request_id
    )
  );

create policy "participants can send messages" on public.equipment_messages
  for insert with check (
    auth.uid()::integer = sender_id and
    auth.uid()::integer in (
      select renter_id from public.equipment_rental_requests where id = rental_request_id
      union
      select owner_id from public.equipment_rental_requests where id = rental_request_id
    )
  );

