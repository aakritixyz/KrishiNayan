-- Equipment & Input Sharing Feature for KrishiNayan
-- Community rental marketplace for farming equipment and input sharing
-- Run with `npx supabase db push` after linking the project

-- Equipment Listings Table
create table if not exists public.equipment_listings (
  id integer generated by default as identity primary key,
  owner_id integer not null references public.users(id) on delete cascade,
  
  -- Equipment Details
  equipment_type varchar not null,
  equipment_name varchar not null,
  brand varchar,
  model varchar,
  year_manufactured integer,
  condition varchar not null,
  
  -- Pricing
  rental_price_per_day double precision not null,
  rental_price_per_hour double precision,
  security_deposit double precision default 0,
  
  -- Location
  state varchar not null,
  district varchar not null,
  village varchar,
  latitude double precision not null,
  longitude double precision not null,
  location_description varchar,
  
  -- Availability
  is_available boolean default true,
  available_from date not null,
  available_until date,
  booked_dates jsonb,
  
  -- Media
  photos jsonb,
  primary_photo varchar,
  
  -- Description
  description text,
  specifications jsonb,
  usage_instructions text,
  safety_notes text,
  
  -- Status
  status varchar default 'active',
  verification_status varchar default 'pending',
  listing_quality_score double precision default 0,
  
  -- Metadata
  view_count integer default 0,
  inquiry_count integer default 0,
  rental_count integer default 0,
  
  created_at timestamp default now(),
  updated_at timestamp default now()
);

-- Equipment Rental Requests Table
create table if not exists public.equipment_rental_requests (
  id integer generated by default as identity primary key,
  listing_id integer not null references public.equipment_listings(id) on delete cascade,
  renter_id integer not null references public.users(id) on delete cascade,
  owner_id integer not null references public.users(id) on delete cascade,
  
  -- Rental Details
  requested_start_date date not null,
  requested_end_date date not null,
  requested_duration_hours integer,
  total_cost double precision not null,
  security_deposit_amount double precision,
  
  -- Status Workflow
  status varchar default 'pending',
  rejection_reason varchar,
  
  -- Communication
  message text,
  owner_response text,
  
  -- Pickup/Return
  pickup_location varchar,
  pickup_time varchar,
  return_condition varchar,
  return_notes text,
  
  -- Agreement
  agreed_terms boolean default false,
  agreement_signed_at timestamp,
  
  -- Completion
  actual_start_date date,
  actual_end_date date,
  actual_return_date date,
  
  created_at timestamp default now(),
  updated_at timestamp default now()
);

-- Equipment Reviews Table
create table if not exists public.equipment_reviews (
  id integer generated by default as identity primary key,
  rental_request_id integer not null references public.equipment_rental_requests(id) on delete cascade,
  listing_id integer not null references public.equipment_listings(id) on delete cascade,
  
  -- Reviewer info
  reviewer_id integer not null references public.users(id) on delete cascade,
  reviewee_id integer not null references public.users(id) on delete cascade,
  review_type varchar not null,
  
  -- Ratings
  overall_rating integer not null check (overall_rating >= 1 and overall_rating <= 5),
  equipment_condition_rating integer check (equipment_condition_rating >= 1 and equipment_condition_rating <= 5),
  communication_rating integer check (communication_rating >= 1 and communication_rating <= 5),
  punctuality_rating integer check (punctuality_rating >= 1 and punctuality_rating <= 5),
  value_rating integer check (value_rating >= 1 and value_rating <= 5),
  
  -- Review Content
  title varchar,
  comment text,
  
  -- Trust signals
  verified_rental boolean default true,
  helpful_count integer default 0,
  
  created_at timestamp default now(),
  updated_at timestamp default now()
);

