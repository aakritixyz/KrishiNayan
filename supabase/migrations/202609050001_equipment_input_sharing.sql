-- Bulk Purchase Groups Table (Phase 2)
create table if not exists public.bulk_purchase_groups (
  id integer generated by default as identity primary key,
  organizer_id integer not null references public.users(id) on delete cascade,
  
  -- Group Details
  input_type varchar not null,
  input_name varchar not null,
  target_quantity double precision not null,
  current_quantity double precision default 0,
  unit varchar not null,
  
  -- Pricing
  target_price_per_unit double precision not null,
  estimated_savings_percentage double precision,
  
  -- Location
  state varchar not null,
  district varchar not null,
  meeting_point varchar,
  
  -- Timeline
  deadline date not null,
  pickup_date date,
  
  -- Status
  status varchar default 'open',
  
  -- Participants
  max_participants integer,
  current_participants integer default 0,
  
  created_at timestamp default now(),
  updated_at timestamp default now()
);

-- Bulk Purchase Participants Table (Phase 2)
create table if not exists public.bulk_purchase_participants (
  id integer generated by default as identity primary key,
  group_id integer not null references public.bulk_purchase_groups(id) on delete cascade,
  participant_id integer not null references public.users(id) on delete cascade,
  
  -- Commitment
  committed_quantity double precision not null,
  committed_amount double precision not null,
  
  -- Status
  status varchar default 'committed',
  
  -- Payment
  payment_status varchar default 'pending',
  payment_amount double precision,
  paid_at timestamp,
  
  created_at timestamp default now(),
  updated_at timestamp default now()
);

-- Equipment Categories Table
create table if not exists public.equipment_categories (
  id integer generated by default as identity primary key,
  name varchar not null unique,
  name_hi varchar,
  display_order integer default 0,
  icon varchar,
  is_active boolean default true,
  created_at timestamp default now()
);

-- User Equipment Trust Score Table
create table if not exists public.user_equipment_trust (
  id integer generated by default as identity primary key,
  user_id integer not null unique references public.users(id) on delete cascade,
  
  -- Trust Metrics
  overall_trust_score double precision default 50,
  as_owner_rating double precision,
  as_renter_rating double precision,
  
  -- Activity Metrics
  total_listings integer default 0,
  total_rentals_as_owner integer default 0,
  total_rentals_as_renter integer default 0,
  successful_completions integer default 0,
  cancellations integer default 0,
  disputes integer default 0,
  
  -- Verification
  identity_verified boolean default false,
  phone_verified boolean default false,
  equipment_verified_count integer default 0,
  
  -- Response Time
  average_response_time_hours double precision,
  
  updated_at timestamp default now()
);

-- Equipment Messages Table (for in-app chat)
create table if not exists public.equipment_messages (
  id integer generated by default as identity primary key,
  rental_request_id integer not null references public.equipment_rental_requests(id) on delete cascade,
  sender_id integer not null references public.users(id) on delete cascade,
  message text not null,
  message_type varchar default 'text', -- 'text', 'voice', 'system'
  voice_note_url varchar,
  is_read boolean default false,
  read_at timestamp,
  created_at timestamp default now()
);

-- Indexes for Equipment Search Performance
create index if not exists ix_equipment_listings_location on public.equipment_listings(state, district, status);
create index if not exists ix_equipment_listings_type_status on public.equipment_listings(equipment_type, status);
create index if not exists ix_equipment_listings_owner on public.equipment_listings(owner_id, status);
create index if not exists ix_equipment_listings_available_dates on public.equipment_listings(available_from, available_until, status);
create index if not exists ix_equipment_listings_coordinates on public.equipment_listings(latitude, longitude);
create index if not exists ix_equipment_listings_verification on public.equipment_listings(verification_status, status);

-- Rental Request Indexes
create index if not exists ix_equipment_rental_requests_listing on public.equipment_rental_requests(listing_id, status);
create index if not exists ix_equipment_rental_requests_renter on public.equipment_rental_requests(renter_id, status);
create index if not exists ix_equipment_rental_requests_owner on public.equipment_rental_requests(owner_id, status);
create index if not exists ix_equipment_rental_requests_dates on public.equipment_rental_requests(requested_start_date, requested_end_date);

-- Review Indexes
create index if not exists ix_equipment_reviews_listing on public.equipment_reviews(listing_id);
create index if not exists ix_equipment_reviews_reviewee on public.equipment_reviews(reviewee_id, review_type);
create index if not exists ix_equipment_reviews_rental on public.equipment_reviews(rental_request_id);

-- Input Sharing Indexes
create index if not exists ix_input_sharing_location on public.input_sharing_listings(state, district, status);
create index if not exists ix_input_sharing_type on public.input_sharing_listings(input_type, status);

-- Bulk Purchase Indexes
create index if not exists ix_bulk_purchase_groups_status on public.bulk_purchase_groups(status, deadline);
create index if not exists ix_bulk_purchase_participants_group on public.bulk_purchase_participants(group_id, status);

-- Trust Score Indexes
create index if not exists ix_user_equipment_trust_user on public.user_equipment_trust(user_id);
create index if not exists ix_user_equipment_trust_score on public.user_equipment_trust(overall_trust_score);

-- Message Indexes
create index if not exists ix_equipment_messages_request on public.equipment_messages(rental_request_id, created_at);
create index if not exists ix_equipment_messages_sender on public.equipment_messages(sender_id);

