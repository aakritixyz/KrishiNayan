-- The FastAPI backend should connect with the service role/database password,
-- which bypasses RLS. These deny-by-default policies protect the tables if a
-- browser Supabase client is introduced later before user-id claims are mapped.
drop policy if exists "deny direct users access" on public.users;
create policy "deny direct users access" on public.users for all using (false);

drop policy if exists "deny direct farm plots access" on public.farm_plots;
create policy "deny direct farm plots access" on public.farm_plots for all using (false);

drop policy if exists "deny direct scan records access" on public.scan_records;
create policy "deny direct scan records access" on public.scan_records for all using (false);

drop policy if exists "deny direct recovery plans access" on public.recovery_plans;
create policy "deny direct recovery plans access" on public.recovery_plans for all using (false);

drop policy if exists "deny direct recovery tasks access" on public.recovery_tasks;
create policy "deny direct recovery tasks access" on public.recovery_tasks for all using (false);

drop policy if exists "deny direct officer advisories access" on public.officer_advisories;
create policy "deny direct officer advisories access" on public.officer_advisories for all using (false);

